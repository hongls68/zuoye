/* ============ 9. 三轴波形 / 传感器示波器（第5周）============
 * 把加速度计从"每秒一个点"改成"20Hz 连续采样 + 攒批上传"，
 * 网页那边就能画出三轴波形和实时姿态孪生。
 *
 * 【为什么是"攒批"而不是"一个点发一次"】
 *   20Hz 意味着每秒 20 个点。这条 Wi-Fi 链路的实测延迟在 3ms~770ms 之间剧烈抖动，
 *   一个点一次 HTTP 会让建连次数暴涨、成功率低到没法看。
 *   攒一批发一次，**丢一批只少一段波形，不会把连接搞死** —— 批量上传对丢包天然容错。
 *
 * 【WAVE_HZ 与 WAVE_BATCH_SAMPLES 的关系】
 *   一批的时长 = WAVE_BATCH_SAMPLES / WAVE_HZ 秒。默认 100/20 = **5 秒一批**。
 *   服务端会拿这两个数反推时间轴（板子没对时时唯一还准的摆法），
 *   所以**改了这两个值，服务端那边不用改** —— 它读的是报文里带的数。
 *
 * 【WAVE_RING_SAMPLES 是缓冲，不是批次大小】
 *   采样任务独立跑，主循环负责发。两者之间用环形缓冲解耦。
 *   512 点 @20Hz = 25.6 秒，是照着"开机后连 Wi-Fi 可能要等十几秒"留的余量。
 *   必须保持 2 的幂（代码里用位与取模，不是 2 的幂会算错，有编译期断言兜着）。
 *
 * 【丢样本会如实上报，不要指望它被悄悄补上】
 *   缓冲满了丢的是**最老的**样本（示波器要看"现在"），丢了多少会随下一批
 *   报给服务端（dropped 字段）。服务端据此决定还能不能用采样率反推时间轴。
 */
#define WAVE_ENABLE             1       /* 1=启用波形采样；0=退回每秒一个点 */
#define WAVE_HZ                 20      /* 采样率（Hz）—— 改这里要连着看下面的批大小 */
#define WAVE_BATCH_SAMPLES      100     /* 一批攒多少点（100/20 = 5 秒一批）*/
#define WAVE_RING_SAMPLES       512     /* 环形缓冲容量（2 的幂，25.6 秒）*/
#define WAVE_UPLOAD_TIMEOUT_MS  8000    /* 批量上传单次 HTTP 超时（与其它通道分开）*/

/* ============ 10. 断网 Flash 缓存（补传）============
 *
 * 对应计划书 4.2 的缓冲层：「断网期间捕获帧自动驻留 Flash 待恢复上传」。
 * 计划书原话是「**断网缓冲不是可选项**」，所以这一段不是锦上添花。
 *
 * 【为什么必须做】
 *   摄像头抓帧本身不需要网络。原来主循环在断网时会 `continue`，
 *   于是连帧都不抓 —— 断网期间的画面**直接消失**。
 *   这和"网络断了"是两件事：画面丢不丢，取决于我们抓不抓。
 *
 * 【★ 补传的帧绝不能冒充"刚拍的"】
 *   这是本功能最容易做错的地方，也是它与第 2 周题眼（"证明这是新采集"）
 *   互为反面的地方：补传帧的**采集时刻在过去**。
 *   所以板端补传时会带上三个额外的头，服务端据此把它标成 source=backlog：
 *     X-Source: backlog     显式声明这是补传
 *     X-Buffered-Us         这一帧在队列里待了多久（微秒）
 *     X-Backlog-Dropped     存它的时候，队列已因满而丢弃的更老帧数
 *   服务端会**拒绝**"补传帧 + X-Request-Id"的组合 —— 拿旧帧去当某次远程请求
 *   的观测，正是第 2 周防的那个"旧值冒充"。
 *
 * 【离线抓帧为什么要降频】
 *   分区 3MB，800×600 的 JPEG 单帧约 40~70KB，只装得下 40~70 帧。
 *   若沿用在线时的 2 秒一帧，几十秒就写满了，断网一小时等于只保住最后一分钟。
 *   所以断网时把间隔放宽到 10 秒 —— 换来 7~12 分钟的覆盖窗口。
 *   这是**有意的取舍**，不是参数没调好。
 *
 * 【写满了丢最老，而且如实计数】
 *   和波形的环形缓冲同一个原则：丢最老的（用户关心"刚才发生了什么"），
 *   丢了多少会随下一帧一起报给服务端（backlog_dropped），
 *   画廊里会显示"更老的帧已丢弃 N 帧"。
 *   「我丢了几帧」和「我一帧没丢」是两件事，不能混着说。
 */
#define BACKLOG_ENABLE              1       /* 1=启用断网 Flash 缓存；0=退回"断网就丢帧" */
#define BACKLOG_PARTITION_LABEL     "backlog"  /* 必须与 partitions.csv 里的名字一致 */
#define BACKLOG_MOUNT_POINT         "/backlog"
#define BACKLOG_OFFLINE_PERIOD_MS   10000   /* 断网时的抓帧间隔（比在线的 2 秒慢，见上）*/
#define BACKLOG_MAX_FRAMES          64      /* 队列条数上限（分区空间是硬上限，这是软上限）*/
#define BACKLOG_MAX_FRAME_BYTES     (200*1024)  /* 单帧上限：超过就不入队（防止一张图吃满分区）*/
#define BACKLOG_REPLAY_PER_LOOP     1       /* 每轮主循环最多补传几帧（1 帧/秒，不阻塞主循环）*/

#endif /* APP_CONFIG_H */
