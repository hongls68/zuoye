/* ============ 4. 硬件参数（一般不用改）============
 * 以下为 ESP32-S3-EYE 板载 QMA7981 加速度计的实测引脚，
 * 来源：乐鑫官方用户指南 + 该板型的开源实测工程，两处交叉验证一致。
 */
#define QMA7981_I2C_SDA_GPIO    4       /* 板载 I2C 数据线 */
#define QMA7981_I2C_SCL_GPIO    5       /* 板载 I2C 时钟线 */
#define QMA7981_I2C_ADDR        0x12    /* 7 位从机地址 */
#define QMA7981_CHIP_ID_EXPECT  0xE7    /* 上电自检：读不到这个值说明接线或驱动有问题 */

#define QMA7981_REG_CHIP_ID     0x00    /* 芯片 ID 寄存器 */
#define QMA7981_REG_X_LSB       0x01    /* 数据寄存器 0x01~0x06 */
#define QMA7981_REG_FSR         0x0F    /* RANGE<3:0> 量程寄存器 */
#define QMA7981_REG_BW          0x10    /* BW<4:0> 带宽寄存器（保持复位默认，未显式配置）*/
#define QMA7981_REG_PM          0x11    /* MODE_BIT<7>=1 进 Active；复位后默认是待机 */
#define QMA7981_REG_SOFTRESET   0x36    /* 写 0xB6 软复位 */

/*
 * 量程与灵敏度（依据 QST 原厂数据手册 QMA7981 Rev.A，第 4 页规格表与第 20 页寄存器表）：
 *      RANGE=0001 -> ±2g   -> 4096 LSB/g
 *      RANGE=0010 -> ±4g   -> 2048 LSB/g
 *      RANGE=0100 -> ±8g   -> 1024 LSB/g   ← 本固件采用
 *      RANGE=1000 -> ±16g  ->  512 LSB/g
 *      RANGE=1111 -> ±32g  ->  256 LSB/g
 * 选 ±8g 是因为手持/拿起放下板子时瞬时加速度可能超过 2g，量程太小会削顶。
 * 固件会显式写入该寄存器，不依赖芯片复位默认值，两个宏必须成对修改。
 */
#define QMA7981_RANGE_BITS      0x04    /* 0100 = ±8g */
#define QMA7981_LSB_PER_G       1024.0f /* ±8g 对应 1024 LSB/g（手册标称值）*/

/*
 * 实测标定系数（2026-09-09 标定，针对本块板子）
 *
 * 原理：板子静止时只受重力，三轴合成加速度 |a| 理论上恒为 1.000 g，
 *       与摆放姿态无关。因此这是唯一无需标准器具就能做的现场标定。
 *
 * 实测过程：
 *   第 1 次（板子斜放）：未标定 |a| = 0.9116 → 代入 0.9116
 *   第 2 次（板子姿态有变）：同样系数下 |a| 仅到 0.9266，
 *           反推当前姿态未标定 |a| = 0.8447 → 修正为 0.8447
 *   第 3 次（2026-09-10，板子静置不动）：系数 0.8447 下 |a| = 0.9563
 *           （12 条均值，标准差 0.0081，确认静止）
 *           0.8447 × 0.9563 = 0.8078 → 修正为 0.8078
 *
 * 两次姿态的未标定 |a| 不同（0.9116 / 0.8447 / 0.8078），说明该传感器除灵敏度
 * 误差外还存在**零点偏移**，因此单一比例系数无法在所有姿态下都得到 1.000。
 * 当前系数按最近一次静止姿态整定，使 |a| ≈ 1.000。
 *
 * 用法：换算时除以该系数，使静止时 |a| ≈ 1.000 g，
 *       从而满足「平放时重力所在轴应约为 1.000 g」的检查要求。
 *
 * 【若要更准】把板子**水平静置**，采集若干条算出 |a| 均值，替换此处，
 *            即可让平放姿态（老师检查的姿态）读数最接近 1.000。
 *            彻底消除零点偏移需六面法校准，本课程一般不必。
 */
#define QMA7981_CALIB_SCALE     0.8078f

/*
 * 自检标准：板子水平静止放置时，三轴合成应当约等于 1.000 g（只受重力）。
 * 烧录后先看串口打印，若明显偏离，说明量程宏与实际不符，按上表调整后重新编译。
 */

/* ============ 5. 采集与上报节奏 ============ */
#define SAMPLE_PERIOD_MS        1000    /* 每 1 秒采一次并上传，符合任务要求 */
/*
 * 单次 POST 超时时间。
 * 原来写 5000ms，在无线链路丢包时（尤其摄像头那 20~25KB 的整帧 POST）
 * 容易在「连上了但数据/响应还没回来」时被误判为失败，故放宽到 8000ms。
 * 注意：这只影响"等多久放弃"，不改变传输本身；链路真丢包时加大它也只是延后失败。
 */
#define UPLOAD_TIMEOUT_MS       8000    /* 单次 POST 超时时间 */
#define WIFI_RETRY_INTERVAL_MS  5000    /* Wi-Fi 掉线后的重连间隔（不重启设备） */

/* ============ 6. 摄像头（板载 OV2640，可选增强功能）============ */
/*
 * 以下开关控制「摄像头采集 + 无线实时传图」功能，与原有加速度计功能正交：
 *   - CAMERA_ENABLE = 0 时，本次改动完全不生效，固件退化为原来的纯加速度版本；
 *   - CAMERA_ENABLE = 1 时，板子除了每秒上报加速度，还会按 CAMERA_PERIOD_MS
 *     周期性抓一帧 JPEG 通过 Wi-Fi POST 到服务器的 /api/frame 接口。
 *
 * 板子脱机（充电宝供电）时，只要 Wi-Fi 已配好，抓帧传图与加速度上报都会照常进行，
 * 与是否插电脑 USB 无关。
 */
#define CAMERA_ENABLE           1       /* 1=启用摄像头；0=仅保留加速度计（恢复原状）*/
#define CAMERA_PERIOD_MS        2000    /* 摄像头抓帧并上传周期（实时性与带宽平衡）*/
#define CAMERA_JPEG_QUALITY     12      /* 1=最佳 ~ 63=最差；越小越清晰体积越大 */
/* 分辨率在 firmware/main/camera.c 顶部用 FRAMESIZE_* 指定（改那里即可）：
 * 常用 FRAMESIZE_VGA(640x480) / SVGA(800x600) / XGA(1024x768) / UXGA(1600x1200)。
 * 分辨率越高单帧越大、上传越慢；校园网/热点下建议 VGA~SVGA。 */

/* ============ 7. 远程采集指令通道（第2周）============
 * 板子按 CMD_POLL_INTERVAL_MS 周期向服务器取「待执行指令」，
 * 取到后立即回执，再抓一帧带上 request_id 回传。
 *
 * 【关键】这条通道与上面的周期上报**完全解耦**：
 * 暂停周期上报（或把 SAMPLE_PERIOD_MS 调大）时，命令通道仍然可用 ——
 * 这是课程明确的检查项，不能做成同一个开关。
 *
 * 轮询周期的取舍：取 5 秒是为了让「点击 -> 出图」的等待感可接受；
 * 调大省流量但演示时等待明显，调小则空轮询变多。
 */
#define CMD_ENABLE              1       /* 1=启用远程指令通道；0=退回纯周期上报 */
#define CMD_POLL_INTERVAL_MS    5000    /* 取指令轮询周期 */
#define CMD_TIMEOUT_MS          8000    /* 命令通道单次 HTTP 超时（与上传超时分开）*/

/* ============ 8. 按键触发与本地反馈（第3周）============
 * 与第2周方向相反：这次是**板子主动发起**一件事，网页上的人来回应。
 *
 * 【硬件依据】乐鑫官方 ESP-BSP 的 ESP32-S3-EYE 板级定义
 *   （esp-bsp/bsp/esp32_s3_eye/include/bsp/esp32_s3_eye.h）
 *     BSP_BUTTON_5_IO = GPIO_NUM_0   板载 BOOT 键 —— 板上唯一可自由读取的按键
 *     BSP_LED_1_IO    = GPIO_NUM_3   模组电源指示灯 —— 官方明确支持软件控制
 *
 * 【重要】GPIO3 必须开漏驱动（代码里已用 GPIO_MODE_OUTPUT_OD），
 *   直接推挽输出高电平可能烧掉 LED（官方文档警告，v2.2 板为此加了限流电阻 R83）。
 *
 * 【按键操作】
 *   短按         空闲时发起一次求助；进行中则取消这一次求助
 *   长按 2 秒    强制重新发起（自动取消上一条，换一个新的 event_id）
 *
 * 【LED 反馈（一眼能区分三种状态来源）】
 *   慢闪（1s 周期）  ① 本地已确认 —— 按键受理了，还没发出去
 *   快闪（0.2s 周期）    正在发送到 VPS
 *   常亮             ② VPS 已接收 —— 服务端回了回执，但还没人回应
 *   三连闪×2         ③ 查看者已回应 —— 网页前的人点了回应
 *   长闪 4 次        已取消
 *   急闪 10 次       发送失败
 */
#define HELP_ENABLE             1       /* 1=启用按键求助通道；0=完全关闭 */
#define HELP_BTN_GPIO           0       /* 板载 BOOT 键（官方 BSP: BSP_BUTTON_5_IO）*/
#define HELP_LED_GPIO           3       /* 板载模组电源指示灯（官方 BSP: BSP_LED_1_IO）*/
#define HELP_TIMEOUT_MS         8000    /* 求助通道单次 HTTP 超时 */
#define HELP_LONG_PRESS_MS      2000    /* 长按判定阈值（毫秒）*/
#define HELP_MIN_PRESS_MS       30      /* 短于这个时长视为抖动，忽略 */
#define HELP_DEBOUNCE_SAMPLES   3       /* 连续 N 次（20ms/次）读到同一电平才认账 */

/* 蜂鸣器：**板载没有**（官方 BSP 里 BSP_CAPS_AUDIO_SPEAKER = 0），
 * 必须外接才能用。想用就把 BUZZER_ENABLE 置 1 并填上实际接的引脚。
 * 用 LEDC 输出 2.7kHz 方波：无源蜂鸣器直接可用，有源蜂鸣器也能响。
 * 建议接在载板上（见 hardware/carrier_pcb.svg 的 4P 端子台）。 */
#define BUZZER_ENABLE           0       /* 1=启用外接蜂鸣器 */
#define BUZZER_GPIO             2       /* 仅在 BUZZER_ENABLE=1 时有效（GPIO2 是空闲的排针脚）*/

#endif /* APP_CONFIG_H */
