/* ============ 4. 硬件参数（一般不用改）============
 * 以下为 ESP32-S3-EYE 板载 QMA7981 加速度计的实测引脚，
 * 来源：乐鑫官方用户指南 + 该板型的开源实测工程，两处交叉验证一致。
 */
#define QMA7981_I2C_SDA_GPIO    4       /* 板载 I2C 数据线 */
#define QMA7981_I2C_SCL_GPIO    5       /* 板载 I2C 时钟线 */
#define QMA7981_I2C_ADDR        0x12    /* 7 位从机地址 */
#define QMA7981_CHIP_ID_EXPECT  0xE7    /* 上电自检：读不到这个值说明接线或驱动有问题 */

#define QMA7981_REG_CHIP_ID     0x00    /* 芯片 ID 寄存器 */
#define QMA7981_REG_X_LSB       0x01    /* 数据寄存器 0x01~0x06 */
#define QMA7981_REG_FSR         0x0F    /* RANGE<3:0> 量程寄存器 */
#define QMA7981_REG_BW          0x10    /* BW<4:0> 带宽寄存器（保持复位默认，未显式配置）*/
#define QMA7981_REG_PM          0x11    /* MODE_BIT<7>=1 进 Active；复位后默认是待机 */
#define QMA7981_REG_SOFTRESET   0x36    /* 写 0xB6 软复位 */

/*
 * 量程与灵敏度（依据 QST 原厂数据手册 QMA7981 Rev.A，第 4 页规格表与第 20 页寄存器表）：
 *      RANGE=0001 -> ±2g   -> 4096 LSB/g
 *      RANGE=0010 -> ±4g   -> 2048 LSB/g
 *      RANGE=0100 -> ±8g   -> 1024 LSB/g   ← 本固件采用
 *      RANGE=1000 -> ±16g  ->  512 LSB/g
 *      RANGE=1111 -> ±32g  ->  256 LSB/g
 * 选 ±8g 是因为手持/拿起放下板子时瞬时加速度可能超过 2g，量程太小会削顶。
 * 固件会显式写入该寄存器，不依赖芯片复位默认值，两个宏必须成对修改。
 */
#define QMA7981_RANGE_BITS      0x04    /* 0100 = ±8g */
#define QMA7981_LSB_PER_G       1024.0f /* ±8g 对应 1024 LSB/g（手册标称值）*/

/*
 * 实测标定系数（2026-09-09 标定，针对本块板子）
 *
 * 原理：板子静止时只受重力，三轴合成加速度 |a| 理论上恒为 1.000 g，
 *       与摆放姿态无关。因此这是唯一无需标准器具就能做的现场标定。
 *
 * 实测过程：
 *   第 1 次（板子斜放）：未标定 |a| = 0.9116 → 代入 0.9116
 *   第 2 次（板子姿态有变）：同样系数下 |a| 仅到 0.9266，
 *           反推当前姿态未标定 |a| = 0.8447 → 修正为 0.8447
 *   第 3 次（2026-09-10，板子静置不动）：系数 0.8447 下 |a| = 0.9563
 *           （12 条均值，标准差 0.0081，确认静止）
 *           0.8447 × 0.9563 = 0.8078 → 修正为 0.8078
 *
 * 两次姿态的未标定 |a| 不同（0.9116 / 0.8447 / 0.8078），说明该传感器除灵敏度
 * 误差外还存在**零点偏移**，因此单一比例系数无法在所有姿态下都得到 1.000。
 * 当前系数按最近一次静止姿态整定，使 |a| ≈ 1.000。
 *
 * 用法：换算时除以该系数，使静止时 |a| ≈ 1.000 g，
 *       从而满足「平放时重力所在轴应约为 1.000 g」的检查要求。
 *
 * 【若要更准】把板子**水平静置**，采集若干条算出 |a| 均值，替换此处，
 *            即可让平放姿态（老师检查的姿态）读数最接近 1.000。
 *            彻底消除零点偏移需六面法校准，本课程一般不必。
 */
#define QMA7981_CALIB_SCALE     0.8078f

/*
 * 自检标准：板子水平静止放置时，三轴合成应当约等于 1.000 g（只受重力）。
 * 烧录后先看串口打印，若明显偏离，说明量程宏与实际不符，按上表调整后重新编译。
 */

